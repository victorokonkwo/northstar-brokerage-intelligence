"""INV-06: every execution belongs to exactly one settlement obligation, whose
amount is the sum of its executions' amounts.

Scenarios are generated (orders with several fills over several trading days)
and run through the simulator. The expected amounts are recomputed here.
"""

from collections import Counter
from datetime import UTC, date, datetime, time, timedelta
from decimal import ROUND_HALF_EVEN, Decimal
from typing import Any

from hypothesis import given
from hypothesis import strategies as st

from northstar.common.money import Currency
from northstar.domain.calendar import BUSINESS_TIMEZONE
from northstar.domain.events import TradeExecuted, TradeSettled
from northstar.simulation.scenario import Scenario, generate_events

from factories import policies, xtse

TRADING_DAYS = [
    d for d in (date(2026, 3, 2) + timedelta(days=n) for n in range(60)) if xtse().is_trading_day(d)
]


@st.composite
def scenarios(draw: st.DrawFn) -> Scenario:
    orders = []
    for _ in range(draw(st.integers(min_value=1, max_value=4))):
        days = sorted(draw(st.lists(st.sampled_from(TRADING_DAYS), min_size=1, max_size=4)))
        fills: list[dict[str, Any]] = []
        for n, day in enumerate(days):
            at = datetime.combine(day, time(10, 0), tzinfo=BUSINESS_TIMEZONE).astimezone(
                UTC
            ) + timedelta(minutes=n)
            fills.append(
                {
                    "at": at,
                    "quantity": str(draw(st.integers(min_value=1, max_value=500))),
                    "price": format(
                        draw(
                            st.decimals(min_value=Decimal("0.01"), max_value=Decimal(500), places=4)
                        ),
                        "f",
                    ),
                }
            )
        total = sum(Decimal(f["quantity"]) for f in fills)
        orders.append(
            {
                "at": fills[0]["at"] - timedelta(seconds=1),
                "instrument": "SYNA",
                "side": draw(st.sampled_from(["BUY", "SELL"])),
                "order_type": "MARKET",
                "quantity": str(total),
                "fills": fills,
            }
        )
    return Scenario.model_validate(
        {
            "scenario_id": "generated",
            "description": "generated by Hypothesis",
            "illustrative": True,
            "settlement_time_local": time(12, 0),
            "account": {
                "account_type": "CASH",
                "base_currency": "CAD",
                "opened_at": datetime(2026, 3, 2, 13, 0, tzinfo=UTC),
            },
            "instruments": [
                {
                    "key": "SYNA",
                    "symbol": "SYNA",
                    "name": "Synthetic Alpha Corp.",
                    "market": "XTSE",
                    "asset_class": "EQUITY",
                    "currency": "CAD",
                }
            ],
            "deposits": [],
            "orders": orders,
        }
    )


@given(scenario=scenarios(), seed=st.integers(min_value=0, max_value=1000))
def test_every_execution_settles_in_exactly_one_obligation(scenario: Scenario, seed: int) -> None:
    events = generate_events(scenario, seed, policies())
    executions = {e.payload.execution_id: e.payload for e in events if isinstance(e, TradeExecuted)}
    settlements = [e.payload for e in events if isinstance(e, TradeSettled)]

    membership = Counter(eid for s in settlements for eid in s.execution_ids)
    assert set(membership) == set(executions)
    assert all(count == 1 for count in membership.values())

    for obligation in settlements:
        members = [executions[eid] for eid in obligation.execution_ids]
        assert all(m.settlement_id == obligation.settlement_id for m in members)
        assert all(m.settlement_date == obligation.settlement_date for m in members)
        assert {(m.order_id, m.trade_date) for m in members} == {
            (obligation.order_id, obligation.trade_date)
        }
        expected_amount = sum(
            (m.quantity * m.price * m.multiplier).quantize(
                Decimal("0.01"), rounding=ROUND_HALF_EVEN
            )
            for m in members
        )
        assert obligation.amount == expected_amount
        assert obligation.quantity == sum(m.quantity for m in members)
        assert obligation.currency is Currency.CAD
